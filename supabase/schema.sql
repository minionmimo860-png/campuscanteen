create or replace function public.sync_food_category()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
    new.category := coalesce(nullif(trim(new.category), ''), 'Other');
    insert into public.categories (name)
    values (new.category)
    on conflict (name) do update set name = excluded.name
    returning id into new.category_id;
    return new;
end;
$$;

