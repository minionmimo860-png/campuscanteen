create or replace function public.is_canteen_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = (select auth.uid())
          and role = 'admin'
    );
$$;

create or replace function public.is_canteen_chef()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
    select exists (
        select 1
        from public.profiles
        where id = (select auth.uid())
          and role = 'chef'
    );
$$;

create or replace function public.set_canteen_staff_role(p_profile_id uuid, p_role text)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    if not (select public.is_canteen_admin()) then
        raise exception 'Only a canteen admin can manage staff access.';
    end if;

    if p_role is null or p_role not in ('student', 'chef') then
        raise exception 'Staff role must be student or chef.';
    end if;

    update public.profiles
    set role = p_role
    where id = p_profile_id
      and role in ('student', 'chef');

    if not found then
        raise exception 'Customer or chef profile not found.';
    end if;
end;
$$;

create or replace function public.set_canteen_stock(p_food_id integer, p_stock_quantity integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
    if not (select public.is_canteen_admin()) then
        raise exception 'Only a canteen admin can update stock counts.';
    end if;

    if p_stock_quantity is null or p_stock_quantity < 0 then
        raise exception 'Stock quantity must be zero or more.';
    end if;

    update public.foods
    set stock_quantity = p_stock_quantity
    where id = p_food_id;

    if not found then
        raise exception 'Menu item not found.';
    end if;
end;
$$;

create or replace function public.create_canteen_profile()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
    profile_name text;
    profile_username text;
    profile_phone text;
    profile_delivery_address text;
begin
    profile_name := coalesce(
        nullif(trim(new.raw_user_meta_data ->> 'name'), ''),
        split_part(new.email, '@', 1)
    );
    profile_username := coalesce(
        nullif(trim(new.raw_user_meta_data ->> 'username'), ''),
        'user_' || substr(new.id::text, 1, 8)
    );
    profile_phone := nullif(trim(new.raw_user_meta_data ->> 'phone'), '');
    profile_delivery_address := nullif(trim(new.raw_user_meta_data ->> 'delivery_address'), '');

    insert into public.profiles (id, name, username, email, phone, delivery_address)
    values (new.id, profile_name, profile_username, new.email, profile_phone, profile_delivery_address);

    return new;
end;
$$;

